"""Run the actual generator and compile its outputs, without writing tracked build artifacts."""
import argparse
import csv
import shutil
import subprocess
import tempfile
from pathlib import Path


def run(args, expected=0):
    """运行编译器或生成器，保留 Windows 本地化错误文本。"""
    result = subprocess.run([str(x) for x in args], capture_output=True)
    output = result.stdout + result.stderr
    try:
        output = output.decode('utf-8')
    except UnicodeDecodeError:
        output = output.decode('gb18030', errors='replace')
    if result.returncode != expected:
        raise RuntimeError(output)
    return output


def main():
    """生成临时夹具、检查增量失效并运行实际输出；可同步 Unity 夹具。"""
    parser = argparse.ArgumentParser()
    parser.add_argument('--tool', required=True, help='Built ConfigTool.dll')
    parser.add_argument('--framework-config', required=True, help='DJGameFrameWork/FrameWork/Config directory')
    parser.add_argument('--output', help='Keep generated fixture and compiler outputs here')
    parser.add_argument('--unity-fixtures', help='Write the generated fixtures and runtime checks into an Editor test source file')
    args = parser.parse_args()
    source = Path(__file__).resolve().parent
    root = Path(args.output) if args.output else Path(tempfile.mkdtemp(prefix='DJConfigRegression-'))
    old = root / 'Data/CsvOld'
    old.mkdir(parents=True, exist_ok=True)
    define = root / 'ConfigDefine.xml'
    define.write_text('<definitions><enumDefine/><structDefine/></definitions>', encoding='utf-8')
    with (source / 'Fixtures/Mixed.csv').open(encoding='utf-8-sig', newline='') as stream:
        fixture = list(csv.reader(stream))
    for name, indices in [('Mixed', ['Index_Unique', 'Index_NoUnique']), ('Unique', ['Index_Unique', '']),
                          ('Multi', ['', 'Index_NoUnique']), ('Unindexed', ['', ''])]:
        rows = [list(row) for row in fixture]
        rows[3][:2] = indices
        with (old / (name + '.csv')).open('w', encoding='utf-8', newline='') as stream:
            csv.writer(stream).writerows(rows)
    command = ['dotnet', args.tool, root]
    # 四行表头空表必须生成可由生产解析器读取的零记录CSV，不能是空字符串。
    (old / 'Empty.csv').write_text('ID\nUInt32\nid\nIndex_Unique\n', encoding='utf-8')
    run(command)
    empty_output = (root / 'Data/CsvNew/Empty.csv').read_text(encoding='utf-8-sig')
    assert empty_output and not empty_output.strip(), 'empty tables must contain a blank line, not an empty string'
    print('PASS header-only table generation')
    sets = root / 'Data/CSharp'
    stamp = (sets / 'Mixed_ConfigSet.cs').stat().st_mtime_ns
    run(command)
    assert (sets / 'Mixed_ConfigSet.cs').stat().st_mtime_ns == stamp, 'unchanged inputs should skip output writes'
    print('PASS incremental no-change generation')
    (sets / 'Mixed_ConfigSet.cs').unlink()
    run(command)
    assert (sets / 'Mixed_ConfigSet.cs').exists(), 'missing output must regenerate'
    print('PASS missing-output regeneration')
    stamp = (sets / 'Mixed_ConfigSet.cs').stat().st_mtime_ns
    define.write_text('<definitions><!--changed--><enumDefine/><structDefine/></definitions>', encoding='utf-8')
    run(command)
    assert (sets / 'Mixed_ConfigSet.cs').stat().st_mtime_ns != stamp, 'XML changes must invalidate cache'
    print('PASS definition cache invalidation')
    invalid = old / 'Invalid.csv'
    invalid.write_text('ID,array\nUInt32,Array_UInt32\nid,items\nIndex_Unique,\n1,1;2\n', encoding='utf-8')
    assert 'Array_N' in run(command, 1), 'removed array mode must fail clearly'
    invalid.unlink()
    print('PASS removed semicolon array mode fails with migration message')
    invalid.write_text('ID\nUInt32\nid\nIndex\n1\n', encoding='utf-8')
    run(command, 1)
    invalid.unlink()
    # A failed input may have emitted its row model before its invalid index was encountered.
    for path in sets.glob('Invalid*.cs'):
        path.unlink()
    print('PASS malformed index fails')
    shutil.copy2(source / 'RuntimeChecks.cs', root / 'RuntimeChecks.cs')
    framework = Path(args.framework_config)
    for name in ['IDataConfig.cs', 'IDataConfigLine.cs', 'ConfigParse.cs']:
        shutil.copy2(framework / name, root / name)
    project = root / 'RuntimeChecks.csproj'
    project.write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType>'
                       '<TargetFramework>netcoreapp3.1</TargetFramework></PropertyGroup></Project>', encoding='utf-8')
    print(run(['dotnet', 'build', project, '-c', 'Release', '--ignore-failed-sources']))
    print(run(['dotnet', root / 'bin/Release/netcoreapp3.1/RuntimeChecks.dll']))
    if args.unity_fixtures:
        fragments = [path.read_text(encoding='utf-8-sig') for path in sorted(sets.glob('*.cs')) if path.name != 'ConfigDefine.cs']
        fragments.append((source / 'RuntimeChecks.cs').read_text(encoding='utf-8-sig').replace('namespace UnityEngine { }', ''))
        contents = '// Generated by DJConfigTool/Tests/run_regressions.py; edit the fixture or checks at the source.\n'
        contents += '\n'.join('namespace ConfigToolRegression\n{\n' + text + '\n}\n' for text in fragments)
        destination = Path(args.unity_fixtures)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(contents, encoding='utf-8', newline='\n')
    print('Outputs:', root)


if __name__ == '__main__':
    main()
